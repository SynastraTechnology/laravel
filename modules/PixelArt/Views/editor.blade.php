<script>
// Pixel Art Editor JavaScript
let canvas = document.getElementById('pixel-canvas');
let ctx = null;
let currentColor = '#000000';
let currentTool = 'brush';
let brushSize = 1;
let canvasSize = 32;
let pixelSize = 10;
let history = [];
let historyStep = -1;

// Initialize canvas
function initCanvas() {
    canvas.innerHTML = '';
    canvas.style.width = (canvasSize * pixelSize) + 'px';
    canvas.style.height = (canvasSize * pixelSize) + 'px';
    
    for (let i = 0; i < canvasSize * canvasSize; i++) {
        const pixel = document.createElement('div');
        pixel.className = 'pixel';
        pixel.style.width = pixelSize + 'px';
        pixel.style.height = pixelSize + 'px';
        pixel.style.backgroundColor = '#ffffff';
        pixel.style.border = '1px solid #e5e5e5';
        pixel.style.float = 'left';
        pixel.style.cursor = 'crosshair';
        pixel.dataset.index = i;
        
        pixel.addEventListener('mousedown', handlePixelClick);
        pixel.addEventListener('mouseover', handlePixelHover);
        
        canvas.appendChild(pixel);
    }
    
    saveState();
}

// Event handlers
function handlePixelClick(e) {
    if (e.buttons === 1) { // Left mouse button
        const pixel = e.target;
        const color = currentTool === 'eraser' ? '#ffffff' : currentColor;
        
        if (currentTool === 'fill') {
            fillArea(pixel);
        } else {
            paintPixel(pixel, color);
        }
    }
}

function handlePixelHover(e) {
    if (e.buttons === 1) { // Left mouse button held down
        const pixel = e.target;
        const color = currentTool === 'eraser' ? '#ffffff' : currentColor;
        paintPixel(pixel, color);
    }
}

function paintPixel(pixel, color) {
    pixel.style.backgroundColor = color;
    updatePreview();
}

function fillArea(startPixel) {
    const startColor = startPixel.style.backgroundColor;
    const targetColor = currentTool === 'eraser' ? '#ffffff' : currentColor;
    
    if (startColor === targetColor) return;
    
    const pixels = canvas.querySelectorAll('.pixel');
    const startIndex = parseInt(startPixel.dataset.index);
    const queue = [startIndex];
    const visited = new Set();
    
    while (queue.length > 0) {
        const index = queue.shift();
        if (visited.has(index)) continue;
        
        const pixel = pixels[index];
        if (pixel.style.backgroundColor !== startColor) continue;
        
        pixel.style.backgroundColor = targetColor;
        visited.add(index);
        
        // Check adjacent pixels
        const row = Math.floor(index / canvasSize);
        const col = index % canvasSize;
        
        if (col > 0) queue.push(index - 1);
        if (col < canvasSize - 1) queue.push(index + 1);
        if (row > 0) queue.push(index - canvasSize);
        if (row < canvasSize - 1) queue.push(index + canvasSize);
    }
    
    updatePreview();
}

function updatePreview() {
    const preview = document.getElementById('preview-canvas');
    preview.innerHTML = '';
    preview.style.width = '100%';
    preview.style.height = '100%';
    
    const pixels = canvas.querySelectorAll('.pixel');
    const previewSize = Math.min(preview.offsetWidth, preview.offsetHeight);
    const pixelPreviewSize = previewSize / canvasSize;
    
    for (let i = 0; i < pixels.length; i++) {
        const previewPixel = document.createElement('div');
        previewPixel.style.width = pixelPreviewSize + 'px';
        previewPixel.style.height = pixelPreviewSize + 'px';
        previewPixel.style.backgroundColor = pixels[i].style.backgroundColor;
        previewPixel.style.float = 'left';
        preview.appendChild(previewPixel);
    }
}

// Tool functions
function setColor(color) {
    currentColor = color;
    document.getElementById('custom-color').value = color;
}

function setTool(tool) {
    currentTool = tool;
    document.querySelectorAll('[onclick^="setTool"]').forEach(btn => {
        btn.className = btn.className.replace('bg-blue-100 text-blue-700', 'hover:bg-gray-100');
    });
    event.target.className = 'w-full text-left px-3 py-2 rounded bg-blue-100 text-blue-700';
}

function clearCanvas() {
    const pixels = canvas.querySelectorAll('.pixel');
    pixels.forEach(pixel => pixel.style.backgroundColor = '#ffffff');
    updatePreview();
    saveState();
}

function saveState() {
    const pixels = canvas.querySelectorAll('.pixel');
    const state = Array.from(pixels).map(pixel => pixel.style.backgroundColor);
    
    historyStep++;
    if (historyStep < history.length) {
        history.length = historyStep;
    }
    history.push(state);
}

function undo() {
    if (historyStep > 0) {
        historyStep--;
        restoreState();
    }
}

function redo() {
    if (historyStep < history.length - 1) {
        historyStep++;
        restoreState();
    }
}

function restoreState() {
    const state = history[historyStep];
    const pixels = canvas.querySelectorAll('.pixel');
    pixels.forEach((pixel, index) => {
        pixel.style.backgroundColor = state[index];
    });
    updatePreview();
}

function downloadImage() {
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d');
    canvas.width = canvasSize * 10;
    canvas.height = canvasSize * 10;
    
    const pixels = document.querySelectorAll('#pixel-canvas .pixel');
    pixels.forEach((pixel, index) => {
        const x = (index % canvasSize) * 10;
        const y = Math.floor(index / canvasSize) * 10;
        ctx.fillStyle = pixel.style.backgroundColor;
        ctx.fillRect(x, y, 10, 10);
    });
    
    const link = document.createElement('a');
    link.download = 'pixel-art.png';
    link.href = canvas.toDataURL();
    link.click();
}

// Modal functions
function openSaveModal() {
    document.getElementById('save-modal').classList.remove('hidden');
}

function closeSaveModal() {
    document.getElementById('save-modal').classList.add('hidden');
}

// Event listeners
document.getElementById('brush-size').addEventListener('input', function(e) {
    brushSize = parseInt(e.target.value);
    document.getElementById('brush-size-display').textContent = brushSize;
});

document.getElementById('canvas-size').addEventListener('change', function(e) {
    const [width, height] = e.target.value.split('x').map(Number);
    canvasSize = width;
    document.getElementById('canvas-info').textContent = `${width} × ${height}`;
    initCanvas();
});

document.getElementById('custom-color').addEventListener('change', function(e) {
    setColor(e.target.value);
});

document.getElementById('save-btn').addEventListener('click', openSaveModal);
document.getElementById('save-form').addEventListener('submit', function(e) {
    e.preventDefault();
    // Save logic would go here
    closeSaveModal();
    alert('Pixel art saved successfully!');
});

// Initialize
initCanvas();
